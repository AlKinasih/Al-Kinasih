
# Menyimpan nama dengan whitespace
name = "\tAl Kinasih Guntoro\n"

# Menampilkan nama asli
print("Nama asli:")
print(name)

# Menghapus whitespace di sebelah kiri
print("Menggunakan lstrip():")
print(name.lstrip())

# Menghapus whitespace di sebelah kanan
print("Menggunakan rstrip():")
print(name.rstrip())

# Menghapus whitespace di kedua sisi
print("Menggunakan strip():")
print(name.strip())
