
current_users = ['admin', 'Nai', 'Jevjev', 'Naval', 'Al']

new_users = ['NAI', 'Jevjev', 'Rara', 'Bima', 'Naya']

# Membuat salinan current_users dalam huruf kecil
current_users_lower = [user.lower() for user in current_users]

# Memeriksa username baru
for new_user in new_users:
    if new_user.lower() in current_users_lower:
        print(f"Sorry, {new_user} is already taken. Please enter a new username.")
    else:
        print(f"Great, {new_user} is available!")

